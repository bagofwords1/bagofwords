"""Embedded chat: configuration, trusted host assertions, sessions, threads.

Authentication contract (trusted host assertion, V1):

  The customer's backend already knows who is signed in to its application.
  It signs a short-lived JWT for that employee with the embed's PRIVATE key
  (generated by BOW, shown once, never stored) and the browser hands it to the
  BOW iframe, which exchanges it here for an embed session. BOW verifies with
  the stored PUBLIC key:

    * RS256 only (fixed algorithm allowlist, so no algorithm confusion and no
      "alg: none");
    * ``iss`` == the configured issuer, ``aud`` == the embed's public id;
    * ``iat``/``exp`` present, lifetime <= ASSERTION_MAX_LIFETIME, clock skew
      <= ASSERTION_LEEWAY;
    * ``jti`` present and never seen before for this embed (one-time exchange);
    * ``sub`` equals exactly one organization member's admin-set attribute
      ``embed.subject_attribute`` (Membership.custom_attributes). Email is never
      consulted, nothing is provisioned, no role or group comes from claims.

  Everything else in the assertion is ignored. The organization is the
  embed's; a token can never choose another one.

Sessions are rows in ``oauth_mcp_access_tokens`` with scope ``embed`` and
prefix ``bow_embed_``: they fail every main-application dependency (which
accept JWTs, ``bow_oauth_`` app tokens and API keys) and are accepted only by
``current_embed_session`` on the ``/api/embed`` routes, each of which also
checks that the token's embed is the one in the path.

Threads: one hidden report per (embed, user), ``report_type='embed_chat'``.
The embed's runtime settings are written onto it before every turn, so the
existing enforcement paths (roster, disabled tools, model) apply unchanged and
a settings change needs no host redeploy.
"""
