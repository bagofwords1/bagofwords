ASSERTION_ALGORITHMS = ("RS256",)
ASSERTION_MAX_LIFETIME = timedelta(minutes=10)
ASSERTION_LEEWAY = timedelta(seconds=60)
SESSION_LIFETIME = timedelta(hours=1)
SESSION_TOKEN_PREFIX = "bow_embed_"
SESSION_SCOPE = "embed"
PUBLIC_ID_PREFIX = "emb_"
MAX_CONTEXT_BYTES = 4 * 1024
REPORT_TYPE = "embed_chat"
PLATFORM = "embed"

# Tools the compact chat cannot complete (they need the report page's rich
# interaction or output surfaces). Always off inside an embed, whatever the
# admin's switches say; the admin can only switch MORE off.
FORCED_OFF_TOOLS = (
    "clarify",            # the clarify form (submit_clarify_response) is not rendered here
    "create_artifact", "edit_artifact", "create_doc", "edit_doc",
    "create_scheduled_task", "wait",
    "lists", "generate_image",
    "delegate", "notify", "send_email",
)
assert set(FORCED_OFF_TOOLS) <= set(TOOL_SWITCHES)


def _hash(value: str) -> str:
    return hashlib.sha256(value.encode()).hexdigest()


def _utcnow() -> datetime:
    return datetime.utcnow()


def generate_keypair() -> Tuple[str, str, str]:
    """(private_pem, public_pem, fingerprint). RSA-2048 so every customer stack
    (Java, .NET, Node, Python, PHP, Go) can sign RS256 with a stock library."""
    from cryptography.hazmat.primitives import serialization
    from cryptography.hazmat.primitives.asymmetric import rsa

    key = rsa.generate_private_key(public_exponent=65537, key_size=2048)
    private_pem = key.private_bytes(
        serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8, serialization.NoEncryption()
    ).decode()
    public_pem = key.public_key().public_bytes(
        serialization.Encoding.PEM, serialization.PublicFormat.SubjectPublicKeyInfo
    ).decode()
    return private_pem, public_pem, _hash(public_pem)[:32]


def effective_tools(runtime: Optional[dict]) -> dict:
    """The report ``tools`` setting for an embed thread: everything the compact
    chat cannot render is off, plus whatever the admin switched off."""
    tools = {k: False for k in FORCED_OFF_TOOLS}
    for key, value in ((runtime or {}).get("tools") or {}).items():
        if value is False and key in TOOL_SWITCHES:
            tools[key] = False
    return tools


def bounded_context(context: Optional[Dict[str, Any]]) -> Optional[Dict[str, Any]]:
    """Host context is LLM-visible task data: bounded, JSON-only, never authority."""
    if context is None:
        return None
    if not isinstance(context, dict):
        raise AppError.bad_request(ErrorCode.EMBED_CONTEXT_TOO_LARGE, "context must be an object")
    try:
        size = len(json.dumps(context, ensure_ascii=False, default=str).encode("utf-8"))
    except (TypeError, ValueError):
        raise AppError.bad_request(ErrorCode.EMBED_CONTEXT_TOO_LARGE, "context must be JSON")
    if size > MAX_CONTEXT_BYTES:
        raise AppError.bad_request(ErrorCode.EMBED_CONTEXT_TOO_LARGE, "context is too large",
                                   limit=MAX_CONTEXT_BYTES, size=size)
    return context


@dataclass
class EmbedSessionContext:
    embed: Embed
    user: User
    organization: Organization
    membership: Membership
    token_record: OAuthAccessToken


class EmbedService:

    # ── configuration ─────────────────────────────────────────────────

    async def list_embeds(self, db: AsyncSession, organization: Organization) -> List[Embed]:
        rows = (await db.execute(
            select(Embed).where(
                Embed.organization_id == str(organization.id),
                Embed.deleted_at.is_(None),
            ).order_by(Embed.created_at.asc())
        )).scalars().all()
        return list(rows)

    async def get_embed(self, db: AsyncSession, organization: Organization, embed_id: str) -> Embed:
        embed = (await db.execute(
            select(Embed).where(
                Embed.id == str(embed_id),
                Embed.organization_id == str(organization.id),
                Embed.deleted_at.is_(None),
            )
        )).scalar_one_or_none()
        if embed is None:
            raise AppError.not_found(ErrorCode.EMBED_NOT_FOUND, "Embed not found")
        return embed

    async def get_by_public_id(self, db: AsyncSession, public_id: str) -> Optional[Embed]:
        return (await db.execute(
            select(Embed).where(Embed.public_id == str(public_id), Embed.deleted_at.is_(None))
        )).scalar_one_or_none()

    async def _validate_runtime(self, db: AsyncSession, organization: Organization, runtime: EmbedRuntime) -> dict:
        """Agents and model must belong to this organization. Pure-shape rules
        already ran in the schema."""
        from app.models.data_source import DataSource
        from app.models.llm_model import LLMModel

        if runtime.data_source_ids:
            found = set((await db.execute(
                select(DataSource.id).where(
                    DataSource.id.in_(runtime.data_source_ids),
                    DataSource.organization_id == str(organization.id),
                    DataSource.deleted_at.is_(None),
                )
            )).scalars().all())
            if any(x not in found for x in runtime.data_source_ids):
                raise AppError.bad_request(ErrorCode.EMBED_CONFIG_INVALID, "Unknown agent(s)", field="data_source_ids")
        if runtime.model_id:
            model = (await db.execute(
                select(LLMModel.id).where(
                    LLMModel.id == runtime.model_id,
                    LLMModel.organization_id == str(organization.id),
                    LLMModel.deleted_at.is_(None),
                )
            )).scalar_one_or_none()
            if model is None:
                raise AppError.bad_request(ErrorCode.EMBED_CONFIG_INVALID, "Unknown model", field="model_id")
        return runtime.model_dump()

    @staticmethod
    def _validate_branding(branding: EmbedBranding, current: Optional[dict] = None) -> dict:
        from app.settings.config import settings

        data = branding.model_dump()
        if data.get("locale") and data["locale"] not in settings.bow_config.i18n.enabled_locales:
            raise AppError.bad_request(ErrorCode.EMBED_CONFIG_INVALID, "Locale is not enabled", field="locale")
        # The logo is managed by its own upload/delete routes.
        data["logo_key"] = (current or {}).get("logo_key")
        return data

    async def create_embed(self, db: AsyncSession, organization: Organization, user: User, payload: EmbedCreate):
        """Returns (embed, private_key_pem). The private key is not stored."""
        private_pem, public_pem, fingerprint = generate_keypair()
        embed = Embed(
            organization_id=str(organization.id),
            public_id=PUBLIC_ID_PREFIX + secrets.token_hex(10),
            name=payload.name,
            enabled=payload.enabled,
            allowed_origins=list(payload.allowed_origins),
            issuer=payload.issuer,
            subject_attribute=payload.subject_attribute,
            public_key=public_pem,
            key_fingerprint=fingerprint,
            epoch=1,
            runtime=await self._validate_runtime(db, organization, payload.runtime),
            branding=self._validate_branding(payload.branding),
            revision=1,
            created_by_user_id=str(user.id),
        )
        db.add(embed)
        await db.commit()
        await db.refresh(embed)
        return embed, private_pem

    async def update_embed(self, db: AsyncSession, organization: Organization, embed_id: str, payload: EmbedUpdate) -> Embed:
        embed = await self.get_embed(db, organization, embed_id)
        if int(payload.revision) != int(embed.revision):
            raise AppError.conflict(ErrorCode.EMBED_REVISION_CONFLICT, "The embed was changed by someone else",
                                    revision=embed.revision)
        was_enabled = bool(embed.enabled)
        if payload.name is not None:
            embed.name = payload.name.strip()
        if payload.allowed_origins is not None:
            embed.allowed_origins = list(payload.allowed_origins)
        if payload.issuer is not None:
            embed.issuer = payload.issuer.strip()
        if payload.subject_attribute is not None:
            embed.subject_attribute = payload.subject_attribute
        if payload.enabled is not None:
            embed.enabled = bool(payload.enabled)
        if payload.runtime is not None:
            embed.runtime = await self._validate_runtime(db, organization, payload.runtime)
        if payload.branding is not None:
            embed.branding = self._validate_branding(payload.branding, embed.branding)
        if was_enabled and not embed.enabled:
            # Disabling revokes every live session at once.
            embed.epoch = int(embed.epoch or 1) + 1
        embed.revision = int(embed.revision or 1) + 1
        await db.commit()
        await db.refresh(embed)
        return embed

    async def rotate_key(self, db: AsyncSession, organization: Organization, embed_id: str):
        """New keypair, new epoch: assertions signed with the old key and every
        session issued so far stop working immediately."""
        embed = await self.get_embed(db, organization, embed_id)
        private_pem, public_pem, fingerprint = generate_keypair()
        embed.public_key = public_pem
        embed.key_fingerprint = fingerprint
        embed.epoch = int(embed.epoch or 1) + 1
        embed.revision = int(embed.revision or 1) + 1
        await db.commit()
        await db.refresh(embed)
        return embed, private_pem

    async def revoke_sessions(self, db: AsyncSession, organization: Organization, embed_id: str) -> Embed:
        embed = await self.get_embed(db, organization, embed_id)
        embed.epoch = int(embed.epoch or 1) + 1
        await db.commit()
        await db.refresh(embed)
        return embed

    async def delete_embed(self, db: AsyncSession, organization: Organization, embed_id: str) -> None:
        embed = await self.get_embed(db, organization, embed_id)
        now = _utcnow()
        embed.deleted_at = now
        embed.enabled = False
        embed.epoch = int(embed.epoch or 1) + 1
        # Threads go with the embed; agents, connections and users are shared
        # and untouched.
        threads = (await db.execute(
            select(Report).where(Report.embed_id == str(embed.id), Report.deleted_at.is_(None))
        )).scalars().all()
        for report in threads:
            report.deleted_at = now
        await db.commit()

    async def set_logo(self, db: AsyncSession, organization: Organization, embed_id: str, raw: bytes, content_type: str) -> Embed:
        import os
        from io import BytesIO

        from PIL import Image

        embed = await self.get_embed(db, organization, embed_id)
        if (content_type or "").lower() not in ("image/png", "image/jpeg", "image/jpg"):
            raise AppError.bad_request(ErrorCode.EMBED_CONFIG_INVALID, "Unsupported image type. Use PNG or JPEG", field="logo")
        if len(raw) > 512 * 1024:
            raise AppError.bad_request(ErrorCode.EMBED_CONFIG_INVALID, "Logo too large. Max 512KB", field="logo")
        try:
            image = Image.open(BytesIO(raw)).convert("RGBA")
        except Exception:
            raise AppError.bad_request(ErrorCode.EMBED_CONFIG_INVALID, "Invalid image file", field="logo")
        width, height = image.size
        scale = min(256 / width, 128 / height, 1.0)
        if scale < 1.0:
            image = image.resize((int(width * scale), int(height * scale)), Image.Resampling.LANCZOS)
        base_dir = os.path.abspath(os.path.join(os.getcwd(), "uploads", "branding"))
        os.makedirs(base_dir, exist_ok=True)
        filename = f"embed-{embed.id}-{hashlib.sha256(raw).hexdigest()[:16]}.png"
        buf = BytesIO()
        image.save(buf, format="PNG")
        with open(os.path.join(base_dir, filename), "wb") as fh:
            fh.write(buf.getvalue())
        branding = dict(embed.branding or {})
        branding["logo_key"] = filename
        embed.branding = branding
        embed.revision = int(embed.revision or 1) + 1
        await db.commit()
        await db.refresh(embed)
        return embed

    async def remove_logo(self, db: AsyncSession, organization: Organization, embed_id: str) -> Embed:
        embed = await self.get_embed(db, organization, embed_id)
        branding = dict(embed.branding or {})
        branding["logo_key"] = None
        embed.branding = branding
        embed.revision = int(embed.revision or 1) + 1
        await db.commit()
        await db.refresh(embed)
        return embed

    @staticmethod
    def logo_path(embed: Embed) -> Optional[str]:
        import os

        key = (embed.branding or {}).get("logo_key")
        if not key or "/" in key or "\\" in key or not key.startswith("embed-"):
            return None
        path = os.path.abspath(os.path.join(os.getcwd(), "uploads", "branding", key))
        return path if os.path.isfile(path) else None

    @staticmethod
    def public_branding(embed: Embed) -> Dict[str, Any]:
        branding = dict(embed.branding or {})
        logo_key = branding.pop("logo_key", None)
        branding["logo_url"] = f"/api/embed/{embed.public_id}/logo?v={logo_key[-16:-4]}" if logo_key else None
        branding["display_name"] = branding.get("display_name") or embed.name
        return branding

    # ── counters for the settings page ────────────────────────────────

    async def counters(self, db: AsyncSession, embed: Embed) -> Dict[str, int]:
        members = await self._members_with_attribute(db, embed)
        now = _utcnow()
        rows = (await db.execute(
            select(OAuthAccessToken.exchange_context).where(
                OAuthAccessToken.embed_id == str(embed.id),
                OAuthAccessToken.deleted_at.is_(None),
                OAuthAccessToken.expires_at > now,
            )
        )).scalars().all()
        # Sessions minted under an older epoch are dead even if unexpired.
        live_sessions = sum(1 for ctx in rows if (ctx or {}).get("embed_epoch") == embed.epoch)
        conversations = (await db.execute(
            select(func.count(Report.id)).where(Report.embed_id == str(embed.id), Report.deleted_at.is_(None))
        )).scalar() or 0
        return {"mapped_members": len(members), "active_sessions": live_sessions, "conversations": int(conversations)}

    async def _members_with_attribute(self, db: AsyncSession, embed: Embed) -> List[Membership]:
        rows = (await db.execute(
            select(Membership).where(
                Membership.organization_id == str(embed.organization_id),
                Membership.user_id.isnot(None),
                Membership.custom_attributes.isnot(None),
            )
        )).scalars().all()
        key = embed.subject_attribute
        return [m for m in rows if str((m.custom_attributes or {}).get(key, "") or "").strip()]

    async def mapped_members(self, db: AsyncSession, embed: Embed) -> List[Dict[str, Any]]:
        members = await self._members_with_attribute(db, embed)
        if not members:
            return []
        users = {
            str(u.id): u for u in (await db.execute(
                select(User).where(User.id.in_([str(m.user_id) for m in members]))
            )).scalars().all()
        }
        out = []
        for m in members:
            u = users.get(str(m.user_id))
            out.append({
                "membership_id": str(m.id),
                "user_id": str(m.user_id),
                "name": getattr(u, "name", None),
                "email": getattr(u, "email", None),
                "subject": str((m.custom_attributes or {}).get(embed.subject_attribute)),
                "is_active": bool(getattr(u, "is_active", False)),
            })
        return out

    # ── trusted host assertion → session ──────────────────────────────

    async def authenticate_assertion(self, db: AsyncSession, embed: Embed, assertion: str) -> Tuple[User, Membership]:
        """Verify an assertion and return (user, membership). Typed errors only;
        the reason never echoes the token."""
        if not embed.enabled:
            raise AppError.forbidden(ErrorCode.EMBED_DISABLED, "This embed is disabled")
        claims = self.decode_assertion(embed, assertion)
        await self._consume_jti(db, embed, claims)
        return await self.resolve_member_by_subject(db, embed, str(claims["sub"]))

    @staticmethod
    def decode_assertion(embed: Embed, assertion: str, *, now: Optional[datetime] = None) -> Dict[str, Any]:
        """Signature, algorithm, issuer, audience, time window and required
        claims. Pure (no DB) so the matrix is unit-testable."""
        try:
            claims = jwt.decode(
                assertion,
                embed.public_key,
                algorithms=list(ASSERTION_ALGORITHMS),
                audience=embed.public_id,
                issuer=embed.issuer,
                leeway=ASSERTION_LEEWAY.total_seconds(),
                options={"require": ["exp", "iat", "sub", "jti", "iss", "aud"]},
            )
        except jwt.ExpiredSignatureError:
            raise AppError.unauthorized(ErrorCode.EMBED_ASSERTION_INVALID, "Assertion expired", reason="expired")
        except jwt.ImmatureSignatureError:
            raise AppError.unauthorized(ErrorCode.EMBED_ASSERTION_INVALID, "Assertion is not valid yet", reason="not_yet_valid")
        except jwt.InvalidAudienceError:
            raise AppError.unauthorized(ErrorCode.EMBED_ASSERTION_INVALID, "Assertion audience mismatch", reason="audience")
        except jwt.InvalidIssuerError:
            raise AppError.unauthorized(ErrorCode.EMBED_ASSERTION_INVALID, "Assertion issuer mismatch", reason="issuer")
        except jwt.MissingRequiredClaimError as e:
            raise AppError.unauthorized(ErrorCode.EMBED_ASSERTION_INVALID, "Assertion is missing a claim",
                                        reason="missing_claim", claim=getattr(e, "claim", None))
        except jwt.InvalidAlgorithmError:
            raise AppError.unauthorized(ErrorCode.EMBED_ASSERTION_INVALID, "Assertion algorithm not allowed", reason="algorithm")
        except jwt.PyJWTError:
            raise AppError.unauthorized(ErrorCode.EMBED_ASSERTION_INVALID, "Assertion could not be verified", reason="signature")

        sub = str(claims.get("sub") or "").strip()
        jti = str(claims.get("jti") or "").strip()
        if not sub or not jti or len(jti) > 255 or len(sub) > 256:
            raise AppError.unauthorized(ErrorCode.EMBED_ASSERTION_INVALID, "Assertion subject or id invalid", reason="claims")
        try:
            iat = datetime.utcfromtimestamp(int(claims["iat"]))
            exp = datetime.utcfromtimestamp(int(claims["exp"]))
        except (TypeError, ValueError, OverflowError, OSError):
            raise AppError.unauthorized(ErrorCode.EMBED_ASSERTION_INVALID, "Assertion timestamps invalid", reason="claims")
        current = now or _utcnow()
        if exp - iat > ASSERTION_MAX_LIFETIME or iat > current + ASSERTION_LEEWAY:
            raise AppError.unauthorized(ErrorCode.EMBED_ASSERTION_INVALID, "Assertion lifetime too long", reason="lifetime")
        return {"sub": sub, "jti": jti, "iat": iat, "exp": exp}

    async def _consume_jti(self, db: AsyncSession, embed: Embed, claims: Dict[str, Any]) -> None:
        """Record the assertion id; a duplicate is a replay. The unique
        constraint makes this safe under concurrency."""
        now = _utcnow()
        # Opportunistic sweep so the table stays small; failures are harmless.
        try:
            stale = (await db.execute(
                select(EmbedAssertionReplay).where(EmbedAssertionReplay.expires_at < now - ASSERTION_LEEWAY)
                .limit(200)
            )).scalars().all()
            for row in stale:
                await db.delete(row)
            if stale:
                await db.flush()
        except Exception:
            await db.rollback()
        db.add(EmbedAssertionReplay(embed_id=str(embed.id), jti=claims["jti"],
                                    expires_at=claims["exp"] + ASSERTION_LEEWAY))
        try:
            await db.commit()
        except IntegrityError:
            await db.rollback()
            raise AppError.unauthorized(ErrorCode.EMBED_ASSERTION_REPLAYED, "Assertion already used")

    async def resolve_member_by_subject(self, db: AsyncSession, embed: Embed, subject: str) -> Tuple[User, Membership]:
        """The one member whose admin-set attribute equals ``subject``.

        Only ``custom_attributes`` counts (admin-only, never member-editable or
        IdP-synced), zero matches = not mapped, two = ambiguous: both refuse,
        neither ever falls back to email or creates anything."""
        key = embed.subject_attribute
        candidates = (await db.execute(
            select(Membership).where(
                Membership.organization_id == str(embed.organization_id),
                Membership.user_id.isnot(None),
                Membership.custom_attributes.isnot(None),
            )
        )).scalars().all()
        matches = [m for m in candidates if str((m.custom_attributes or {}).get(key, "") or "").strip() == subject]
        if not matches:
            raise AppError.unauthorized(ErrorCode.EMBED_IDENTITY_UNMAPPED, "No member is mapped to this identity")
        if len(matches) > 1:
            raise AppError.unauthorized(ErrorCode.EMBED_IDENTITY_AMBIGUOUS, "More than one member is mapped to this identity")
        membership = matches[0]
        user = (await db.execute(select(User).where(User.id == str(membership.user_id)))).scalar_one_or_none()
        if user is None or not getattr(user, "is_active", False):
            raise AppError.forbidden(ErrorCode.EMBED_USER_INACTIVE, "This account is inactive")
        return user, membership

    async def issue_session(self, db: AsyncSession, embed: Embed, user: User) -> Tuple[str, OAuthAccessToken]:
        token = SESSION_TOKEN_PREFIX + secrets.token_urlsafe(32)
        record = OAuthAccessToken(
            token_hash=_hash(token),
            client_id=f"embed:{embed.public_id}"[:64],
            user_id=str(user.id),
            organization_id=str(embed.organization_id),
            scope=SESSION_SCOPE,
            expires_at=_utcnow() + SESSION_LIFETIME,
            exchange_context={
                "embed_epoch": int(embed.epoch or 1),
                "user_epoch": int(getattr(user, "session_epoch", 0) or 0),
            },
            embed_id=str(embed.id),
        )
        db.add(record)
        await db.commit()
        await db.refresh(record)
        return token, record

    async def resolve_session(self, db: AsyncSession, token: str) -> Optional[EmbedSessionContext]:
        """Live session or None. Re-asserted on every request: expiry, embed
        enabled + epoch, user active + session epoch, organization membership."""
        if not token or not token.startswith(SESSION_TOKEN_PREFIX):
            return None
        record = (await db.execute(
            select(OAuthAccessToken).where(
                OAuthAccessToken.token_hash == _hash(token),
                OAuthAccessToken.deleted_at.is_(None),
            )
        )).scalar_one_or_none()
        if record is None or record.scope != SESSION_SCOPE or not record.embed_id:
            return None
        if record.expires_at < _utcnow():
            return None
        embed = (await db.execute(
            select(Embed).where(Embed.id == str(record.embed_id), Embed.deleted_at.is_(None))
        )).scalar_one_or_none()
        if embed is None or not embed.enabled:
            return None
        ctx = record.exchange_context or {}
        if int(ctx.get("embed_epoch", -1)) != int(embed.epoch or 1):
            return None
        user = (await db.execute(
            select(User).where(User.id == str(record.user_id), User.is_active.is_(True))
        )).scalar_one_or_none()
        if user is None or int(ctx.get("user_epoch", -1)) != int(getattr(user, "session_epoch", 0) or 0):
            return None
        organization = (await db.execute(
            select(Organization).where(Organization.id == str(embed.organization_id), Organization.deleted_at.is_(None))
        )).scalar_one_or_none()
        if organization is None:
            return None
        membership = (await db.execute(
            select(Membership).where(
                Membership.user_id == str(user.id),
                Membership.organization_id == str(organization.id),
            )
        )).scalars().first()
        if membership is None:
            return None
        return EmbedSessionContext(embed=embed, user=user, organization=organization,
                                   membership=membership, token_record=record)

    async def revoke_session(self, db: AsyncSession, record: OAuthAccessToken) -> None:
        record.deleted_at = _utcnow()
        await db.commit()

