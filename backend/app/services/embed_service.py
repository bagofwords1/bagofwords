    async def effective_agent_ids(self, db: AsyncSession, embed: Embed, organization: Organization, user: User,
                                  requested: Optional[List[str]] = None) -> List[str]:
        """admin roster ∩ the user's own accessible live agents (∩ the user's
        pick, when the embed allows picking). An empty admin roster is empty —
        never Auto."""
        from app.ai.tools.implementations.agent_focus_common import accessible_agents
        from app.services.data_source_service import DataSourceService

        allowed = {str(x) for x in ((embed.runtime or {}).get("data_source_ids") or [])}
        if not allowed:
            return []
        mine = await accessible_agents(db, organization, user)
        effective = [str(ds.id) for ds in mine if str(ds.id) in allowed and DataSourceService.is_execution_live(ds)]
        if requested is not None:
            if not (embed.runtime or {}).get("allow_agent_selection"):
                raise AppError.forbidden(ErrorCode.EMBED_AGENT_FORBIDDEN, "Agent selection is not allowed here")
            wanted = {str(x) for x in requested}
            if not wanted.issubset(set(effective)):
                raise AppError.forbidden(ErrorCode.EMBED_AGENT_FORBIDDEN, "Agent not available in this embed")
            effective = [x for x in effective if x in wanted]
        return effective

    async def find_thread(self, db: AsyncSession, embed: Embed, user: User) -> Optional[Report]:
        return (await db.execute(
            select(Report).where(
                Report.embed_id == str(embed.id),
                Report.user_id == str(user.id),
                Report.report_type == REPORT_TYPE,
                Report.deleted_at.is_(None),
            ).limit(1)
        )).scalar_one_or_none()

    async def resolve_thread(self, db: AsyncSession, embed: Embed, user: User, agent_ids: List[str]) -> Report:
        """Get-or-create the employee's thread and sync the embed's runtime
        settings onto it. Concurrency: the partial unique index on
        (embed_id, user_id) makes the second creator lose and re-read."""
        from app.services.artifact_chat_service import ArtifactChatService

        thread = await self.find_thread(db, embed, user)
        if thread is None:
            thread = Report(
                title=f"{embed.name}",
                slug=f"embed-chat-{uuid.uuid4().hex[:12]}",
                status="draft",
                report_type=REPORT_TYPE,
                mode="chat",
                user_id=str(user.id),
                organization_id=str(embed.organization_id),
                embed_id=str(embed.id),
            )
            db.add(thread)
            try:
                await db.flush()
            except IntegrityError:
                await db.rollback()
                thread = await self.find_thread(db, embed, user)
                if thread is None:
                    raise
        runtime = embed.runtime or {}
        thread.model_id = runtime.get("model_id") or None
        thread.reasoning_effort = runtime.get("reasoning_effort") or None
        thread.tools = effective_tools(runtime)
        thread.follow_ups = runtime.get("follow_ups")
        thread.suggest_instructions = runtime.get("suggest_instructions", False)
        await ArtifactChatService.sync_roster(db, thread, agent_ids)
        await db.commit()
        await db.refresh(thread)
        return thread


