"""Create Demo Dataset Tool — design, confirm, generate and install mock data (training mode).

One tool, one approval:

1. The agent passes a declarative spec (tables, columns, keys, row counts,
   generation hints, suggested agents with icons). It is validated first; a
   broken spec comes back as ``invalid_spec`` with errors to fix.
2. The tool pauses on a confirmation card. The user approves (with the
   suggested agents they kept ticked) or rejects with feedback, which goes
   back to the agent to revise and call again.
3. On approval each table is generated by the org's SMALL default model as
   sandboxed pandas/numpy code, validated (PK/FK/types/nulls/dates) with
   retries, written to SQLite at a server-chosen path, registered as a
   connection, and the ticked agents are created on it with their tables,
   icons, starters and instructions — attached to this training session.

Gates: org setting ``enable_demo_data_generation`` (and training mode, via
``allowed_modes``), plus org ``manage_connections`` — the same permission that
guards ``POST /connections``. Creating the agents additionally needs
``create_data_source``; without it only the connection is created.
"""

from __future__ import annotations

import asyncio
import logging
import os
import uuid
from typing import Any, AsyncIterator, Dict, List, Optional, Type

from pydantic import BaseModel

from app.ai.tools.base import Tool
from app.ai.tools.metadata import ToolMetadata
from app.ai.tools.schemas.create_demo_dataset import (
    CreateDemoDatasetInput,
    CreateDemoDatasetOutput,
    CreatedDemoAgent,
    DemoTableStat,
)
from app.ai.tools.schemas.events import (
    ToolEndEvent,
    ToolErrorEvent,
    ToolEvent,
    ToolProgressEvent,
    ToolStartEvent,
)

logger = logging.getLogger(__name__)

TOOL_NAME = "create_demo_dataset"
SETTING_KEY = "enable_demo_data_generation"
# Review pause + generation must fit inside timeout_seconds (the runner's
# hard deadline for this tool); keepalives keep its idle watchdog quiet.
REVIEW_TIMEOUT_S = 240.0
GENERATION_KEEPALIVE_S = 10.0


def demo_generation_enabled(organization_settings) -> bool:
    """Org toggle (default off)."""
    if organization_settings is None:
        return False
    try:
        cfg = organization_settings.get_config(SETTING_KEY)
    except Exception:
        return False
    if cfg is None:
        return False
    return bool(getattr(cfg, "value", cfg))


class CreateDemoDatasetTool(Tool):

    @property
    def metadata(self) -> ToolMetadata:
        return ToolMetadata(
            name=TOOL_NAME,
            description=(
                "ACTION (training): design and create a realistic MOCK demo database (SQLite) for any "
                "domain — finance, sales, HR, e-commerce, logs/monitoring, machine/IoT, etc. — plus "
                "suggested agents on top. Pass the full spec: tables (snake_case), typed columns with "
                "descriptions, one primary key per table, foreign keys as 'table.column', realistic "
                "row counts, generation_hint per important column, dataset-level realism_notes "
                "(cross-table rules, seasonality, incidents), a date range ending today or earlier, "
                "and 1-4 suggested agents (each with ONE emoji icon, its active tables, conversation "
                "starters and business-definition instructions). The user reviews it on a card "
                "(ticks which agents to create) and approves or rejects with feedback; on reject, "
                "revise per the feedback and call again. Read the demo-data skill first."
            ),
            category="action",
            version="1.0.0",
            input_schema=CreateDemoDatasetInput.model_json_schema(),
            output_schema=CreateDemoDatasetOutput.model_json_schema(),
            max_retries=0,
            timeout_seconds=600,
            idempotent=False,
            required_permissions=["manage_connections"],
            allowed_modes=["training"],
            tags=["training", "connection", "agent-building", "demo-data"],
            examples=[
                {
                    "input": {
                        "name": "Demo – HR",
                        "domain": "HR for a 300-person software company",
                        "icon": "👥",
                        "date_range_start": "2023-01-01",
                        "date_range_end": "2025-06-30",
                        "tables": [
                            {"name": "departments", "description": "One row per department", "row_count": 8,
                             "columns": [
                                 {"name": "department_id", "type": "integer", "primary_key": True, "description": "Department id"},
                                 {"name": "name", "type": "text", "description": "Department name",
                                  "generation_hint": "Engineering, Sales, Marketing, Support, Finance, HR, Product, Operations"}]},
                            {"name": "employees", "description": "One row per employee (current and former)", "row_count": 340,
                             "columns": [
                                 {"name": "employee_id", "type": "integer", "primary_key": True, "description": "Employee id"},
                                 {"name": "department_id", "type": "integer", "references": "departments.department_id", "description": "Home department"},
                                 {"name": "hire_date", "type": "date", "description": "First day", "generation_hint": "hiring waves in Q1 and Q3"},
                                 {"name": "termination_date", "type": "date", "nullable": True, "description": "Last day; NULL if active", "generation_hint": "~15% annual attrition, always after hire_date"},
                                 {"name": "salary", "type": "real", "description": "Annual base salary USD", "generation_hint": "lognormal by level/department, Engineering highest"}]},
                        ],
                        "realism_notes": ["Engineering is ~40% of headcount", "Attrition spikes after the annual review in March"],
                        "agents": [{"name": "People Analytics", "icon": "👥", "tables": ["employees", "departments"],
                                    "description": "Headcount, attrition and compensation",
                                    "conversation_starters": ["What is monthly attrition by department?"],
                                    "instructions": ["Attrition rate = terminations in period / average headcount in period."]}],
                    },
                    "description": "HR dataset with one suggested agent.",
                }
            ],
        )

    @property
    def input_model(self) -> Type[BaseModel]:
        return CreateDemoDatasetInput

    @property
    def output_model(self) -> Type[BaseModel]:
        return CreateDemoDatasetOutput

    # ------------------------------------------------------------------

    def _end(self, output: CreateDemoDatasetOutput, summary: str, artifacts: Optional[list] = None) -> ToolEndEvent:
        if not output.message:
            output.message = summary
        return ToolEndEvent(type="tool.end", payload={
            "output": output.model_dump(),
            "observation": {"summary": summary, "artifacts": artifacts or []},
        })

    async def run_stream(self, tool_input: Dict[str, Any], runtime_ctx: Dict[str, Any]) -> AsyncIterator[ToolEvent]:
        try:
            spec = CreateDemoDatasetInput(**(tool_input or {}))
        except Exception as e:
            yield ToolErrorEvent(type="tool.error", payload={"error": f"Invalid input: {e}", "code": "INVALID_INPUT"})
            return

        yield ToolStartEvent(type="tool.start", payload={
            "name": spec.name,
            "domain": spec.domain,
            "tables": [{"name": t.name, "row_count": t.row_count} for t in spec.tables],
            "agents": [a.name for a in spec.agents],
        })

        db = runtime_ctx.get("db")
        organization = runtime_ctx.get("organization")
        user = runtime_ctx.get("user")
        report = runtime_ctx.get("report")
        org_settings = runtime_ctx.get("settings") or runtime_ctx.get("organization_settings")
        if not all([db, organization, user]):
            yield ToolErrorEvent(type="tool.error", payload={"error": "Missing runtime context.", "code": "MISSING_CONTEXT"})
            return

        try:
            if org_settings is None:
                org_settings = await organization.get_settings(db)
        except Exception:
            org_settings = None
        if not demo_generation_enabled(org_settings):
            yield self._end(
                CreateDemoDatasetOutput(success=False, status="disabled"),
                "Demo data generation is turned off for this organization (AI Settings → Demo data generation).",
            )
            return

        # ---- Permissions (route decorators don't cover the tool path) ----
        from app.core.permission_resolver import resolve_permissions
        resolved = await resolve_permissions(db, str(user.id), str(organization.id))
        if not resolved.has_org_permission("manage_connections"):
            yield self._end(
                CreateDemoDatasetOutput(success=False, status="permission_denied"),
                "Creating a demo dataset creates a connection, which requires the 'manage connections' permission.",
            )
            return
        can_create_agents = resolved.has_org_permission("create_data_source")

        # ---- Spec checks ----
        from app.schemas.demo_dataset_schema import validate_spec
        errors = validate_spec(spec)
        if errors:
            yield self._end(
                CreateDemoDatasetOutput(success=False, status="invalid_spec", errors=errors),
                "The dataset spec has problems — fix them and call create_demo_dataset again: " + " | ".join(errors),
            )
            return

        from app.services.demo_data.installer import MAX_GENERATED_PER_ORG, count_generated
        if await count_generated(db, str(organization.id)) >= MAX_GENERATED_PER_ORG:
            yield self._end(
                CreateDemoDatasetOutput(success=False, status="limit_reached"),
                f"This organization already has {MAX_GENERATED_PER_ORG} generated demo datasets. "
                "Delete one (its connection) before creating another.",
            )
            return

        # ---- Small default model ----
        from app.services.llm_service import LLMService
        try:
            model = await LLMService().get_default_model(db, organization, user, is_small=True)
        except Exception as e:
            logger.warning("create_demo_dataset: small model lookup failed: %s", e)
            model = None
        if model is None:
            yield self._end(
                CreateDemoDatasetOutput(success=False, status="no_model"),
                "No LLM model is configured to generate the data.",
            )
            return
        model_label = getattr(model, "name", None) or getattr(model, "model_id", None)

        # ---- Review: one approval, with the agents the user kept ticked ----
        from app.ai.tools.confirmation import KIND_BUILTIN_TOOL, stream_user_confirmation
        review: Dict[str, Any] = {}
        async for ev in stream_user_confirmation(
            runtime_ctx,
            kind=KIND_BUILTIN_TOOL,
            tool_name=TOOL_NAME,
            payload={
                "dataset_name": spec.name,
                "can_create_agents": can_create_agents,
                "model": model_label,
                "agents": [a.name for a in spec.agents],
            },
            result=review,
            timeout_s=REVIEW_TIMEOUT_S,
        ):
            yield ev

        decision = (review.get("response") or {}).get("response") or {}
        feedback = (decision.get("feedback") or "").strip() or None if isinstance(decision, dict) else None
        if review.get("timed_out"):
            yield self._end(
                CreateDemoDatasetOutput(success=False, status="timed_out"),
                "The proposal was not reviewed in time; nothing was created. Ask the user whether to propose it again.",
            )
            return
        if not review.get("approved"):
            summary = "The user rejected the proposal; nothing was created."
            if feedback:
                summary += f" Their feedback: \"{feedback}\". Revise the spec accordingly and call create_demo_dataset again."
            else:
                summary += " Ask what they would like changed before proposing again."
            yield self._end(CreateDemoDatasetOutput(success=False, status="rejected", feedback=feedback), summary)
            return

        chosen_names = decision.get("agents") if isinstance(decision, dict) else None
        if isinstance(chosen_names, list):
            wanted = {str(n).strip().lower() for n in chosen_names}
            chosen = [a for a in spec.agents if a.name.strip().lower() in wanted]
        else:
            chosen = [a for a in spec.agents if a.selected]

        # ---- Generate ----
        try:
            await db.commit()  # release the session (SQLite single writer) while we generate
        except Exception:
            pass

        from app.ai.llm import LLM
        from app.dependencies import async_session_maker
        from app.services.demo_data.generator import DemoDatasetGenerator, TableGenerationError, write_sqlite

        llm = LLM(model, reasoning_effort="off", usage_session_maker=async_session_maker)

        async def _inference(system: str, prompt: str) -> str:
            return await asyncio.to_thread(llm.inference, prompt, system=system, usage_scope="demo_data_generation")

        total = len(spec.tables)
        state: Dict[str, Dict[str, Any]] = {t.name: {"state": "queued"} for t in spec.tables}
        queue: asyncio.Queue = asyncio.Queue()

        def _progress(p: Dict[str, Any]) -> None:
            name = p.get("table")
            if name in state:
                state[name] = {**state[name], **{k: v for k, v in p.items() if k != "table"}}
            queue.put_nowait(True)

        def _snapshot(stage: str, **extra) -> ToolProgressEvent:
            done = sum(1 for s in state.values() if s.get("state") == "done")
            return ToolProgressEvent(type="tool.progress", payload={
                "stage": stage, "timing": False, "done": done, "total": total,
                "tables": [{"name": n, **s} for n, s in state.items()],
                "agents": [a.name for a in chosen], **extra,
            })

        yield _snapshot("generating", model=model_label)
        generator = DemoDatasetGenerator(_inference)
        task = asyncio.create_task(generator.generate(spec, _progress))
        try:
            while not task.done():
                try:
                    await asyncio.wait_for(queue.get(), timeout=GENERATION_KEEPALIVE_S)
                    while not queue.empty():
                        queue.get_nowait()
                except asyncio.TimeoutError:
                    pass
                sig = runtime_ctx.get("sigkill_event")
                if sig is not None and sig.is_set():
                    task.cancel()
                    break
                yield _snapshot("generating", model=model_label)
            result = await task
        except asyncio.CancelledError:
            yield self._end(CreateDemoDatasetOutput(success=False, status="failed"), "Generation was stopped.")
            return
        except TableGenerationError as e:
            yield self._end(
                CreateDemoDatasetOutput(success=False, status="failed", errors=[f"{e.table}: {e.message}"], model=model_label),
                f"Could not generate table '{e.table}' after {e.attempts} attempts ({e.message[:300]}). "
                "Simplify that table's hints/columns or row count and call create_demo_dataset again.",
            )
            return
        except Exception as e:
            logger.exception("create_demo_dataset: generation failed")
            yield self._end(CreateDemoDatasetOutput(success=False, status="failed", model=model_label), f"Generation failed: {e}")
            return

        # ---- Write + install ----
        from app.services.demo_data import installer
        dataset_id = str(uuid.uuid4())
        path = installer.dataset_path(str(organization.id), dataset_id)
        yield _snapshot("writing", model=model_label)
        try:
            size = await asyncio.to_thread(write_sqlite, path, spec, result.frames)
        except Exception as e:
            logger.exception("create_demo_dataset: write failed")
            try:
                os.remove(path)
            except Exception:
                pass
            yield self._end(CreateDemoDatasetOutput(success=False, status="failed"), f"Writing the database failed: {e}")
            return

        # Install on its OWN session: the services below may roll back on a
        # conflict, and a rollback on the agent's shared session would expire
        # the run's own objects (completion/execution) mid-loop.
        yield _snapshot("connecting", model=model_label)
        from sqlalchemy import select as _select
        from sqlalchemy.orm import selectinload as _selectinload
        from app.models.organization import Organization as _Org
        from app.models.report import Report as _Report
        from app.models.user import User as _User
        org_id, user_id = str(organization.id), str(user.id)
        report_id = str(report.id) if report is not None else None
        created_conn_id: Optional[str] = None
        try:
            async with async_session_maker() as s:
                s_org = await s.get(_Org, org_id)
                s_user = await s.get(_User, user_id)
                connection = await installer.create_connection(
                    s, s_org, s_user, spec, dataset_id=dataset_id, path=path,
                    icon=installer.emoji_token(spec.icon),
                )
                created_conn_id = str(connection.id)
                install = installer.InstallResult(connection_id=created_conn_id, connection_name=connection.name)
                if chosen and can_create_agents:
                    yield _snapshot("creating_agents", model=model_label)
                    s_report = None
                    if report_id:
                        s_report = (await s.execute(
                            _select(_Report).options(_selectinload(_Report.data_sources)).where(_Report.id == report_id)
                        )).scalar_one_or_none()
                    install = await installer.create_agents(s, s_org, s_user, connection, chosen, report=s_report)
                elif chosen:
                    install.skipped_agents = [{"name": a.name, "reason": "permission_denied",
                                               "detail": "Creating agents requires the create_data_source permission."}
                                              for a in chosen]
        except Exception as e:
            logger.exception("create_demo_dataset: install failed")
            if created_conn_id:  # don't leave a connection pointing at a deleted file
                try:
                    from app.services.connection_service import ConnectionService
                    async with async_session_maker() as s:
                        await ConnectionService().delete_connection(
                            s, created_conn_id, await s.get(_Org, org_id), await s.get(_User, user_id))
                except Exception as ce:
                    logger.warning("create_demo_dataset: cleanup of connection %s failed: %s", created_conn_id, ce)
            installer.remove_generated_file({"database": path, installer.GENERATED_KEY: True})
            yield self._end(CreateDemoDatasetOutput(success=False, status="failed"), f"Creating the connection failed: {e}")
            return

        # The agents were attached on another session; let this run see them.
        if report is not None and install.agents:
            try:
                await db.refresh(report, ["data_sources"])
            except Exception as e:
                logger.warning("create_demo_dataset: report refresh failed: %s", e)

        try:
            from app.ee.audit.service import audit_service
            await audit_service.log(
                db=db, organization_id=str(organization.id), action="data_source.demo_generated",
                user_id=str(user.id), resource_type="connection", resource_id=install.connection_id,
                details={"name": install.connection_name, "domain": spec.domain, "tables": len(spec.tables),
                         "rows": result.total_rows, "agents": [a.name for a in install.agents]},
            )
        except Exception:
            pass

        out = CreateDemoDatasetOutput(
            success=True,
            status="created",
            connection_id=install.connection_id,
            connection_name=install.connection_name,
            tables=[DemoTableStat(name=t.name, rows=t.rows, attempts=t.attempts) for t in result.tables],
            total_rows=result.total_rows,
            file_size_bytes=size,
            seconds=result.seconds,
            model=model_label,
            agents=[CreatedDemoAgent(**a.__dict__) for a in install.agents],
            skipped_agents=install.skipped_agents,
            warnings=result.warnings[:20],
        )
        agent_bits = ", ".join(f"{a.name} ({len(a.active_tables)} tables)" for a in install.agents) or "no agents"
        summary = (
            f"Created demo connection '{install.connection_name}' with {len(result.tables)} tables / "
            f"{result.total_rows:,} rows, and {agent_bits}. The agents are attached to this session — "
            "you can now explore the data, refine instructions, or create evals."
        )
        if install.skipped_agents:
            summary += " Skipped: " + "; ".join(f"{s['name']} ({s['reason']})" for s in install.skipped_agents) + "."
        yield self._end(out, summary, artifacts=[
            {"type": "agent", "id": a.data_source_id, "name": a.name} for a in install.agents
        ])
