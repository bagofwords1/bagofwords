"""Append-only transcript and the single seam that renders it to a provider.

Replaces the rebuild-one-user-message pattern: turns accumulate, and
``to_model_messages`` is the only place parts become provider messages. It
feeds the per-client ``_translate_messages`` implementations that already exist.

The ladder (``fit_to_budget``) decays oldest-first and never splits a tool call
from its result.
"""
from __future__ import annotations

from typing import Optional

from app.ai.llm.types import Message
from app.ai.context.replay_args import compact_replayed_args
from app.ai.context.parts import (
    Outcome,
    Part,
    TextPart,
    ThinkingPart,
    Tier,
    ToolCallPart,
    ToolResultPart,
    Turn,
    estimate_tokens,
)

# Turns at the tail that are never decayed — the model must see the step it
# just took in full, plus the one before it for continuity.
PROTECT_LAST_TURNS = 4

# Head-only cut applied to a single rendered tool result (see to_model_messages).
# Named because tools that must fit their own payload under it budget against
# this constant rather than a copy of the number.
MAX_RESULT_CHARS = 100_000

# Tool-supplied images (rendered PDF pages, screenshots): only the newest
# MAX_RETAINED_IMAGES stay in context, counted across the whole run whatever
# step they came from. Older results keep their text plus a note saying how to
# re-read the pages. Without a bound every page a run had read was re-sent on
# every later call: a ~50-scan SharePoint list fill passed 1M tokens inside one
# turn. 24 is three full 8-page read_file calls (~60k tokens at 1568 px).
#
# Counted in images, not steps: an earlier 3-step window released a page as
# soon as three note/list/submit steps followed it, and a model reading one
# page per step re-read the same pages over and over (57 reads instead of 24
# in a live run). Steps that carry no images now cost a page nothing.
MAX_RETAINED_IMAGES = 24


def retained_prefix(sizes: list, *, protected: int, cap: int = MAX_RETAINED_IMAGES) -> int:
    """How many image-bearing units to keep, given their image counts
    newest-first. A unit is one tool result (transcript) or one step's images
    (legacy channel) and is kept whole or not at all — never pages 1-3 of 8.

    The first ``protected`` units (the newest step's) are always kept, even
    past the cap: the model must see what it just read, or it re-reads it
    forever. After that, units are kept while they fit under ``cap``, and the
    first one that does not fit ends the run — strict recency, so the kept set
    is always "the most recent reads" with no gaps. Skipping a big result to
    keep a smaller, older one would leave the model holding page images from
    a read it did *before* one it can no longer see, which is harder to
    reason about than "everything since X".
    """
    total = 0
    kept = 0
    for idx, n in enumerate(sizes):
        if idx >= protected and total + n > cap:
            break
        total += n
        kept += 1
    return kept


def _image_source(img: dict) -> dict:
    """Canonical image-block source: ``{"type": "base64"|"url", ...}``.

    Observation images arrive in ImageInput shape (``data``/``media_type``/
    ``source_type``); every client translator keys the source on ``type``, and
    Anthropic rejects the whole request (400, "source.type: Field required")
    when it is missing. Sources already in canonical shape pass through.
    """
    if not isinstance(img, dict) or "type" in img:
        return img
    if img.get("source_type") == "url":
        return {"type": "url", "url": img.get("data", "")}
    return {
        "type": "base64",
        "media_type": img.get("media_type", "image/png"),
        "data": img.get("data", ""),
    }


class Transcript:
    """Ordered typed turns for rehydrated history plus the current agent run."""

    def __init__(self) -> None:
        self.turns: list[Turn] = []
        # Prefix rehydrated from prior completions. Prompt construction places
        # the current ask after this prefix and before turns generated by the
        # current run. Zero preserves the original single-run behavior.
        self.history_turn_count: int = 0

    # -- construction -------------------------------------------------

    def add_user_text(self, text: str) -> None:
        if text:
            self.turns.append(Turn(role="user", parts=[TextPart(text=text)]))

    def add_assistant_step(
        self,
        *,
        text: Optional[str] = None,
        thinking: Optional[ThinkingPart] = None,
        calls: Optional[list] = None,
    ) -> None:
        parts: list[Part] = []
        if thinking is not None:
            parts.append(thinking)
        if text:
            parts.append(TextPart(text=text))
        parts.extend(calls or [])
        if parts:
            self.turns.append(Turn(role="assistant", parts=parts))

    def add_tool_results(self, results: list, *, head_text: Optional[str] = None) -> None:
        """One user turn carrying every result from the batch, plus the
        per-turn head (clock / steering / nudges) if there is one."""
        parts: list[Part] = list(results)
        if head_text:
            parts.append(TextPart(text=head_text))
        if parts:
            self.turns.append(Turn(role="user", parts=parts))
            self.enforce_image_retention()

    # -- images -------------------------------------------------------

    def enforce_image_retention(self) -> int:
        """Release tool images beyond the newest MAX_RETAINED_IMAGES.

        See retained_prefix: whole results, newest first, the newest
        image-bearing step always kept. Results that decayed past FULL lose
        their images regardless. Released images are gone from the part
        itself, so no later render can send them again. Returns the number of
        images released.
        """
        newest = self._newest_image_turn()
        units = []      # FULL results with images, newest first
        protected = 0
        released = 0
        for idx in range(len(self.turns) - 1, -1, -1):
            for p in reversed(self.turns[idx].parts):
                if not isinstance(p, ToolResultPart) or not p.images:
                    continue
                if p.tier is not Tier.FULL:
                    released += p.release_images()
                    continue
                units.append(p)
                if idx == newest:
                    protected += 1
        keep = retained_prefix([len(p.images) for p in units], protected=protected)
        for p in units[keep:]:
            released += p.release_images()
        return released

    def _newest_image_turn(self) -> int:
        """Index of the newest turn whose tool results carry images (-1 if none)."""
        for idx in range(len(self.turns) - 1, -1, -1):
            if any(isinstance(p, ToolResultPart) and p.images for p in self.turns[idx].parts):
                return idx
        return -1

    def image_count(self) -> int:
        return sum(
            len(p.images)
            for t in self.turns
            for p in t.parts
            if isinstance(p, ToolResultPart)
        )

    # -- integrity ----------------------------------------------------

    def repair(self) -> list:
        """Synthesize results for calls that never produced one.

        A cancelled or crashed step leaves an orphaned tool_call; most providers
        reject that outright. Never drop the call — record what happened.
        """
        synthesized = []
        answered = set()
        for t in self.turns:
            answered |= t.tool_result_ids()
        for idx, turn in enumerate(self.turns):
            missing = [
                p for p in turn.parts
                if isinstance(p, ToolCallPart) and p.id not in answered
            ]
            if not missing:
                continue
            parts = [
                ToolResultPart(
                    call_id=p.id,
                    tool_name=p.tool_name,
                    outcome=Outcome.INTERRUPTED,
                    content="The call was interrupted before it produced a result.",
                )
                for p in missing
            ]
            synthesized.extend(parts)
            self.turns.insert(idx + 1, Turn(role="user", parts=parts))
            answered |= {p.call_id for p in parts}
        return synthesized

    def tokens(self) -> int:
        return sum(t.tokens() for t in self.turns)

    # -- the ladder ---------------------------------------------------

    def floor_tokens(self) -> int:
        """Size the ladder cannot reduce below.

        Everything that is not a decayable tool result: the static context and
        the ask (turn 0/1), the protected tail, and every text part. Reporting
        this matters because a budget below the floor is simply unreachable —
        decay will exhaust itself moving a handful of tokens and the real
        problem is elsewhere (usually an oversized schema block).

        Images are reducible everywhere except on the newest image-bearing
        step, which the ladder never touches (see fit_to_budget).
        """
        split = max(len(self.turns) - PROTECT_LAST_TURNS, 0)
        newest = self._newest_image_turn()
        reducible = 0
        for idx, turn in enumerate(self.turns):
            if idx == newest:
                continue
            for p in turn.parts:
                if not isinstance(p, ToolResultPart):
                    continue
                reducible += p.image_tokens()
                if idx < split:
                    # What this part could still give back at its floor tier.
                    at_floor = estimate_tokens(
                        ToolResultPart(
                            call_id=p.call_id, tool_name=p.tool_name,
                            outcome=p.outcome, content=p.content,
                            digest=p.digest, tier=Tier.DROPPED,
                            images_released=p.images_released + len(p.images),
                        ).model_text()
                    )
                    reducible += max(p.tokens - at_floor, 0)
        return max(self.tokens() - reducible, 0)

    def fit_to_budget(self, budget_tokens: int) -> dict:
        """Decay oldest-first until the transcript fits.

        Rungs, cheapest information loss first:

        1. images on results outside the protected tail (oldest first) — the
           heaviest payload, and the model can re-read a page on demand;
        2. digest (a field swap, no LLM call), then dropped bodies — the ids
           survive and results stay re-fetchable through read_query /
           read_artifact / read_file;
        3. images inside the protected tail, oldest first.

        Text in the last PROTECT_LAST_TURNS turns is never touched, so the step
        the model just took is always present in full. The newest step that
        returned images is never touched either — not its images, not its
        text — even when it has aged out of the tail: the model must always
        see the pages it last read, or it re-reads them forever.

        ``reached`` says whether the budget was actually met. It can be False
        even after decaying everything available, because the floor (static
        context + protected tail) is not reducible here — the caller needs to
        know that rather than assume the transcript now fits.
        """
        stats = {
            "digested": 0, "dropped": 0, "images_released": 0,
            "before": self.tokens(), "after": 0,
            "floor": self.floor_tokens(), "reached": True,
        }
        if stats["before"] <= budget_tokens:
            stats["after"] = stats["before"]
            return stats

        split = max(len(self.turns) - PROTECT_LAST_TURNS, 0)
        newest = self._newest_image_turn()
        decayable = [t for i, t in enumerate(self.turns[:split]) if i != newest]
        tail_images = [t for i, t in enumerate(self.turns) if i >= split and i != newest]

        def _results(turns):
            for turn in turns:
                for p in turn.parts:
                    if isinstance(p, ToolResultPart):
                        yield p

        def _done() -> dict:
            stats["after"] = self.tokens()
            stats["reached"] = stats["after"] <= budget_tokens
            return stats

        for p in _results(decayable):
            if p.images:
                stats["images_released"] += p.release_images()
                if self.tokens() <= budget_tokens:
                    return _done()

        for target in (Tier.DIGEST, Tier.DROPPED):
            for p in _results(decayable):
                if p.tier >= target:
                    continue
                p.tier = target
                p.tokens = estimate_tokens(p.model_text())
                stats["digested" if target is Tier.DIGEST else "dropped"] += 1
                if self.tokens() <= budget_tokens:
                    return _done()

        for p in _results(tail_images):
            if p.images:
                stats["images_released"] += p.release_images()
                if self.tokens() <= budget_tokens:
                    return _done()

        return _done()

    # -- the seam -----------------------------------------------------

    def to_model_messages(
        self,
        *,
        provider_name: Optional[str] = None,
        max_result_chars: int = MAX_RESULT_CHARS,
        supports_images: bool = True,
    ) -> list:
        """Render to provider-agnostic ``Message`` objects.

        Owns the concerns that would otherwise be duplicated per client:
        truncation with a visible notice, media hoisting, and signature replay
        gated on the issuing provider (a mid-run fallback must not forward
        another provider's opaque state).
        """
        out: list[Message] = []
        # Results sit in the turn after their calls; look outcomes up front so
        # a successful call's bulky args can be replayed compactly.
        failed_calls = {
            p.call_id
            for t in self.turns
            for p in t.parts
            if isinstance(p, ToolResultPart) and p.is_error
        }
        for turn in self.turns:
            blocks: list[dict] = []
            # Hoisted per-turn, not per-result: Anthropic requires ALL
            # tool_result blocks to sit at the head of the user message, so
            # a multi-result turn must render [tr1, tr2, …, img…], never
            # [tr1, img, tr2, …].
            hoisted_images: list[dict] = []
            for p in turn.parts:
                if isinstance(p, TextPart):
                    if p.text:
                        blocks.append({"type": "text", "text": p.text})

                elif isinstance(p, ThinkingPart):
                    # Replay only to the provider that issued the signature.
                    if p.signature and provider_name and p.provider_name != provider_name:
                        continue
                    if p.text:
                        blocks.append({"type": "text", "text": p.text})

                elif isinstance(p, ToolCallPart):
                    issued = p.replay_args if p.replay_name else p.args
                    args = compact_replayed_args(p.tool_name, issued, succeeded=p.id not in failed_calls)
                    blk = {"type": "tool_use", "id": p.id, "name": p.replay_name or p.tool_name, "input": args}
                    if p.signature and (not provider_name or p.provider_name == provider_name):
                        blk["signature"] = p.signature
                    blocks.append(blk)

                elif isinstance(p, ToolResultPart):
                    body = p.model_text()
                    if len(body) > max_result_chars:
                        body = (
                            body[:max_result_chars]
                            + f"\n… [truncated at {max_result_chars:,} of {len(body):,} chars]"
                        )
                    entry = {"type": "tool_result", "tool_use_id": p.call_id, "content": body}
                    if p.is_error:
                        entry["is_error"] = True
                    blocks.append(entry)
                    # Images cannot live inside a tool_result on every provider,
                    # so hoist them into the same user turn alongside it. A
                    # result past FULL has decayed: its pictures go with it.
                    if p.images and supports_images and p.tier is Tier.FULL:
                        for img in p.images:
                            hoisted_images.append(
                                {"type": "image", "source": _image_source(img)}
                            )

            blocks.extend(hoisted_images)
            if not blocks:
                continue
            if len(blocks) == 1 and blocks[0]["type"] == "text":
                out.append(Message(role=turn.role, content=blocks[0]["text"]))
            else:
                out.append(Message(role=turn.role, content=blocks))
        return out
