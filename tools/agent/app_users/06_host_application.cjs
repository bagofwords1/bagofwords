const { open, check, done, BOW } = require('./lib.cjs')
const out = process.argv[2]
;(async () => {
  const admin = await open({ storageState: out + '/../admin-state.json' })
  const page = await admin.context.newPage(); page.setDefaultTimeout(60000)
  await page.goto(BOW + '/settings/integrations')
  await page.getByText('Connected applications').first().click()
  await page.getByTestId('application-row').filter({ hasText: 'Acme Portal' }).click()
  await page.waitForTimeout(2500)
  await page.getByText('Embedding', { exact: true }).last().click()
  await page.getByTestId('host-app-new-people').waitFor()
  check('the row says what new people join as', /App user/.test(await page.getByTestId('host-app-new-people').innerText()), await page.getByTestId('host-app-new-people').innerText())
  await page.screenshot({ path: `${out}/43-host-app-row.png` })
  await page.getByTestId('host-app-row').locator('button[aria-label]').last().click()
  await page.locator('[role="menuitem"]').first().click()
  const option = page.getByTestId('host-app-new-user-role-app_user')
  await option.scrollIntoViewIfNeeded()
  check('the host application offers "New people join as", app user chosen', await option.isChecked())
  await page.waitForTimeout(500)
  await page.screenshot({ path: `${out}/43-host-app-new-user-role.png` })
  await admin.browser.close(); done(`${out}/06-results.json`); process.exit(process.exitCode || 0)
})().catch(e => { console.error(e); process.exit(2) })
