const { open, signIn, check, done, BOW } = require('./lib.cjs')
const out = process.argv[2]
;(async () => {
  const { browser, context } = await open()
  const { page, api } = await signIn(context, 'member@example.com')
  await page.waitForURL(/\/apps$/, { timeout: 120000 }).catch(() => {})
  check('an app user lands on /apps after sign-in', page.url().endsWith('/apps'), page.url())
  await page.locator('[data-testid="app-launcher"][data-state="ready"]').waitFor()
  await page.locator('[data-testid="app-card"]').first().waitFor()
  await page.waitForTimeout(1500)
  const titles = await page.locator('[data-testid="app-card-title"]').allTextContents()
  // seed_apps.py: two apps, two dashboards (no enabled host) and a doc; not
  // Inventory Lookup or Board Memo (shared with nobody).
  check('the launcher lists everything shared with them: apps, dashboards and docs', JSON.stringify(titles) === JSON.stringify(['Customer Health', 'Onboarding Notes', 'Quarterly Review', 'Sales Assistant', 'Support Desk']), titles)
  const kinds = await page.locator('[data-testid="app-card"]').evaluateAll(cards => cards.map(c => c.dataset.kind))
  check('each card says what it is', JSON.stringify(kinds) === JSON.stringify(['app', 'doc', 'dashboard', 'app', 'dashboard']), kinds)
  check('the kind filter is offered', await page.getByTestId('app-launcher-kinds').count() === 1)
  check('no "Open workspace" link for an app user', await page.getByTestId('app-launcher-open-workspace').count() === 0)
  check('"Request full access" is offered', await page.getByTestId('app-launcher-request-access').count() === 1)
  await page.screenshot({ path: `${out}/01-launcher-app-user.png` })
  for (const path of ['/', '/reports', '/dashboards', '/agents', '/settings/members', '/onboarding']) {
    await page.goto(BOW + path); await page.waitForURL(/\/apps$/, { timeout: 60000 }).catch(() => {})
    check(`${path} sends an app user to /apps`, page.url().endsWith('/apps'), page.url())
  }
  await page.locator('[data-testid="app-card"]').first().waitFor()
  await page.locator('[data-testid="app-card"]', { hasText: 'Customer Health' }).click()
  await page.waitForURL(/\/d\//)
  await page.getByTestId('app-back').waitFor()
  await page.waitForTimeout(4000)
  await page.screenshot({ path: `${out}/02-app-open-back-arrow.png` })
  check('the app\'s back arrow points at the launcher', (await page.getByTestId('app-back').getAttribute('href')) === '/apps', await page.getByTestId('app-back').getAttribute('href'))
  await page.getByTestId('app-back').hover(); await page.waitForTimeout(600)
  await page.screenshot({ path: `${out}/03-app-back-tooltip.png`, clip: { x: 0, y: 0, width: 520, height: 160 } })
  await page.getByTestId('app-back').click(); await page.waitForURL(/\/apps$/)
  check('back returns to the launcher', true)

  // A kind filter, kept in the URL: back from a doc returns to the same view.
  await page.locator('[data-testid="app-card"]').first().waitFor()
  await page.getByTestId('app-launcher-kind-doc').click()
  await page.waitForURL(/\/apps\?kind=doc$/)
  await page.locator('[data-testid="app-card"]', { hasText: 'Onboarding Notes' }).waitFor()
  await page.waitForTimeout(800)
  const docs = await page.locator('[data-testid="app-card-title"]').allTextContents()
  check('the Docs filter lists only the doc', JSON.stringify(docs) === JSON.stringify(['Onboarding Notes']), docs)
  await page.screenshot({ path: `${out}/01b-launcher-docs-filter.png` })
  await page.getByTestId('app-launcher-kind-app').click()
  await page.waitForURL(/\/apps\?kind=app$/)
  await page.waitForFunction(() => document.querySelectorAll('[data-testid="app-card"][data-kind="app"]').length === 2
    && document.querySelectorAll('[data-testid="app-card"]').length === 2)
  check('the Apps filter lists only the apps', true)
  await page.getByTestId('app-launcher-kind-doc').click(); await page.waitForURL(/\/apps\?kind=doc$/)
  await page.locator('[data-testid="app-card"]', { hasText: 'Onboarding Notes' }).click()
  await page.waitForURL(/\/d\/.*back=apps/)
  await page.getByTestId('app-back').waitFor()
  check('back from the doc points at the filtered launcher', (await page.getByTestId('app-back').getAttribute('href')) === '/apps?kind=doc', await page.getByTestId('app-back').getAttribute('href'))
  await page.reload(); await page.getByTestId('app-back').waitFor()
  check('and still does after a reload', (await page.getByTestId('app-back').getAttribute('href')) === '/apps?kind=doc', await page.getByTestId('app-back').getAttribute('href'))
  await page.getByTestId('app-back').click(); await page.waitForURL(/\/apps\?kind=doc$/)
  await page.locator('[data-testid="app-launcher-kind-doc"][aria-pressed="true"]').waitFor()
  check('back returns to the Docs filter', true)
  // A direct link names no origin: an app user still goes to the launcher.
  await page.goto(BOW + new URL(await page.locator('[data-testid="app-card"]').first().evaluate(a => a.href)).pathname)
  await page.getByTestId('app-back').waitFor()
  check('on a direct link back leads to the launcher', (await page.getByTestId('app-back').getAttribute('href')) === '/apps', await page.getByTestId('app-back').getAttribute('href'))
  await page.goto(BOW + '/apps'); await page.locator('[data-testid="app-launcher"][data-state="ready"]').waitFor()
  await page.getByTestId('app-launcher-account').click(); await page.waitForTimeout(500)
  await page.screenshot({ path: `${out}/04-launcher-account-menu.png` })
  await page.keyboard.press('Escape')
  await page.getByTestId('app-launcher-request-access').click()
  await page.getByTestId('app-launcher-access-sent').waitFor()
  await page.screenshot({ path: `${out}/05-launcher-request-sent.png` })
  check('requesting access shows it was sent', true)
  const forbidden = api.filter(l => /^403/.test(l))
  check('no workspace API call was attempted from the launcher or the app', forbidden.length === 0, forbidden.join(' | '))
  // 'Not found parent scope' is logged by the artifact page itself, for every reader (pre-existing).
  const errors = api.filter(l => /^CONSOLE/.test(l) && !/favicon|Failed to load resource|Not found parent scope/.test(l))
  check('no console errors / i18n warnings', errors.length === 0, errors.slice(0, 3).join(' | '))
  await context.storageState({ path: `${out}/../member-state.json` })
  await browser.close(); done(`${out}/01-results.json`)
})().catch(e => { console.error(e); process.exit(2) })
