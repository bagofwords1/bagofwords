const { open, signIn, check, done, BOW } = require('./lib.cjs')
const out = process.argv[2]
;(async () => {
  const { browser, context } = await open()
  const { page, api } = await signIn(context, 'member@example.com')
  await page.waitForURL(/\/apps$/, { timeout: 120000 }).catch(() => {})
  check('an app user lands on /apps after sign-in', page.url().endsWith('/apps'), page.url())
  await page.locator('[data-testid="app-launcher"][data-state="ready"]').waitFor()
  await page.locator('[data-testid="app-card"]').first().waitFor()
  await page.waitForTimeout(1500)
  const titles = await page.locator('[data-testid="app-card-title"]').allTextContents()
  check('the launcher lists exactly the apps shared with them', JSON.stringify(titles) === JSON.stringify(['Customer Health', 'Sales Assistant']), titles)
  check('no "Open workspace" link for an app user', await page.getByTestId('app-launcher-open-workspace').count() === 0)
  check('"Request full access" is offered', await page.getByTestId('app-launcher-request-access').count() === 1)
  await page.screenshot({ path: `${out}/01-launcher-app-user.png` })
  for (const path of ['/', '/reports', '/dashboards', '/agents', '/settings/members', '/onboarding']) {
    await page.goto(BOW + path); await page.waitForURL(/\/apps$/, { timeout: 60000 }).catch(() => {})
    check(`${path} sends an app user to /apps`, page.url().endsWith('/apps'), page.url())
  }
  await page.locator('[data-testid="app-card"]').first().waitFor()
  await page.locator('[data-testid="app-card"]', { hasText: 'Customer Health' }).click()
  await page.waitForURL(/\/d\//)
  await page.getByTestId('app-back').waitFor()
  await page.waitForTimeout(4000)
  await page.screenshot({ path: `${out}/02-app-open-back-arrow.png` })
  check('the app\'s back arrow points at the launcher', (await page.getByTestId('app-back').getAttribute('href')) === '/apps', await page.getByTestId('app-back').getAttribute('href'))
  await page.getByTestId('app-back').hover(); await page.waitForTimeout(600)
  await page.screenshot({ path: `${out}/03-app-back-tooltip.png`, clip: { x: 0, y: 0, width: 520, height: 160 } })
  await page.getByTestId('app-back').click(); await page.waitForURL(/\/apps$/)
  check('back returns to the launcher', true)
  await page.getByTestId('app-launcher-account').click(); await page.waitForTimeout(500)
  await page.screenshot({ path: `${out}/04-launcher-account-menu.png` })
  await page.keyboard.press('Escape')
  await page.getByTestId('app-launcher-request-access').click()
  await page.getByTestId('app-launcher-access-sent').waitFor()
  await page.screenshot({ path: `${out}/05-launcher-request-sent.png` })
  check('requesting access shows it was sent', true)
  const forbidden = api.filter(l => /^403/.test(l))
  check('no workspace API call was attempted from the launcher or the app', forbidden.length === 0, forbidden.join(' | '))
  // 'Not found parent scope' is logged by the artifact page itself, for every reader (pre-existing).
  const errors = api.filter(l => /^CONSOLE/.test(l) && !/favicon|Failed to load resource|Not found parent scope/.test(l))
  check('no console errors / i18n warnings', errors.length === 0, errors.slice(0, 3).join(' | '))
  await context.storageState({ path: `${out}/../member-state.json` })
  await browser.close(); done(`${out}/01-results.json`)
})().catch(e => { console.error(e); process.exit(2) })
