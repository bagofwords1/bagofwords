const { open, check, done, BOW } = require('./lib.cjs')
const out = process.argv[2]
;(async () => {
  // ── admin: role editor and host application setting ──
  const admin = await open({ storageState: out + '/../admin-state.json' })
  const page = await admin.context.newPage(); page.setDefaultTimeout(120000)
  await page.goto(BOW + '/settings/members?tab=roles')
  await page.getByTestId('role-row-app_user').waitFor(); await page.waitForTimeout(1000)
  await page.screenshot({ path: `${out}/40-roles-list.png` })
  check('the built-in app_user role is listed beside admin and member', await page.getByTestId('role-row-member').count() === 1)
  await page.getByTestId('role-row-member').click().catch(() => {})
  await page.getByTestId('role-permissions').waitFor({ timeout: 20000 }).catch(async () => {
    await page.getByTestId('role-actions-member').click(); await page.getByText('Edit', { exact: true }).first().click()
    await page.getByTestId('role-permissions').waitFor()
  })
  await page.waitForTimeout(800)
  const perms = await page.getByTestId('role-permissions').innerText()
  check('the role editor offers "Use the workspace"', /Use the workspace/.test(perms), perms.slice(0, 160).replace(/\s+/g, ' '))
  await page.screenshot({ path: `${out}/41-role-editor-workspace.png` })
  await page.keyboard.press('Escape')

  await page.goto(BOW + '/settings/integrations')
  await page.waitForTimeout(6000)
  await page.screenshot({ path: `${out}/42-integrations.png` })
  await admin.browser.close()

  // ── the launcher in Hebrew (RTL), empty, and on a phone ──
  const he = await open({ storageState: out + '/../member-state.json' })
  const hp = await he.context.newPage(); hp.setDefaultTimeout(120000)
  const warns = []
  hp.on('console', m => { if (/intlify/.test(m.text())) warns.push(m.text().slice(0, 120)) })
  await hp.goto(BOW + '/apps'); await hp.evaluate(() => localStorage.setItem('bow.locale', 'he')); await hp.reload()
  await hp.locator('[data-testid="app-card"]').first().waitFor(); await hp.waitForTimeout(2000)
  check('Hebrew: the page is right-to-left', await hp.evaluate(() => document.documentElement.dir) === 'rtl')
  const body = await hp.locator('[data-testid="app-launcher"]').innerText()
  check('Hebrew: translated, no raw keys', /משותף איתך/.test(body) && !/apps\.[a-zA-Z]+/.test(body), body.slice(0, 120).replace(/\s+/g, ' '))
  check('Hebrew: no i18n warnings on the launcher', warns.length === 0, warns.join(' | '))
  await hp.screenshot({ path: `${out}/50-launcher-hebrew.png` })
  await hp.locator('[data-testid="app-card"]').first().click(); await hp.waitForURL(/\/d\//); await hp.getByTestId('app-back').waitFor(); await hp.waitForTimeout(3000)
  const box = await hp.getByTestId('app-back').boundingBox()
  check('Hebrew: the back arrow sits at the right edge', box && box.x > 1200, JSON.stringify(box))
  await hp.screenshot({ path: `${out}/51-app-hebrew-back.png` })
  await hp.evaluate(() => localStorage.removeItem('bow.locale'))

  await hp.route('**/api/apps', route => route.fulfill({ json: { apps: [], workspace_access: false, access_requested: false } }))
  await hp.goto(BOW + '/apps'); await hp.getByTestId('app-launcher-empty').waitFor(); await hp.waitForTimeout(800)
  await hp.screenshot({ path: `${out}/52-launcher-empty.png` })
  check('with nothing shared, the launcher says so and still offers the request', await hp.getByTestId('app-launcher-request-access').count() === 1)
  await hp.unroute('**/api/apps')
  await he.browser.close()

  const { devices } = require('playwright')
  const { browser } = await open()
  const phone = await browser.newContext({ ...devices['iPhone 13'], storageState: out + '/../member-state.json' })
  const pp = await phone.newPage(); pp.setDefaultTimeout(120000)
  await pp.goto(BOW + '/apps'); await pp.locator('[data-testid="app-card"]').first().waitFor(); await pp.waitForTimeout(1500)
  const overflow = await pp.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth)
  check('phone: no horizontal scroll', overflow <= 0, overflow)
  await pp.screenshot({ path: `${out}/53-launcher-phone.png` })
  await browser.close()
  done(`${out}/05-results.json`); process.exit(process.exitCode || 0)
})().catch(e => { console.error(e); process.exit(2) })
