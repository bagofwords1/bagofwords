const { open, signIn, check, done, BOW } = require('./lib.cjs')
const out = process.argv[2]
;(async () => {
  const { browser, context } = await open()
  const { page, api } = await signIn(context, 'admin@example.com')
  await page.goto(BOW + '/settings/members')
  await page.getByTestId('member-joined-via').first().waitFor()
  await page.waitForTimeout(1500)
  await page.screenshot({ path: `${out}/20-members-app-users.png` })
  const joined = await page.getByTestId('member-joined-via').allTextContents()
  check('the members list says who joined through which application', joined.some(t => /Acme Portal/.test(t)), joined.join(' | '))
  const row = page.locator('tr', { hasText: 'acme.example' }).first()
  check('their role reads "App user"', /App user/.test(await row.innerText()), (await row.innerText()).replace(/\s+/g, ' ').slice(0, 120))
  // The sidebar offers Apps once the organization has any.
  await page.goto(BOW + '/')
  await page.locator('a[href="/apps"]').first().waitFor()
  await page.waitForTimeout(1500)
  await page.screenshot({ path: `${out}/21-workspace-sidebar-apps.png` })
  check('a workspace member has "Apps" in the sidebar', true)
  await page.locator('a[href="/apps"]').first().click(); await page.waitForURL(/\/apps$/)
  await page.locator('[data-testid="app-card"]').first().waitFor(); await page.waitForTimeout(1500)
  check('a workspace member\'s launcher links back to the workspace', await page.getByTestId('app-launcher-open-workspace').count() === 1)
  check('...and offers no access request', await page.getByTestId('app-launcher-access').count() === 0)
  await page.screenshot({ path: `${out}/22-launcher-member.png` })
  await context.storageState({ path: `${out}/../admin-state.json` })
  await browser.close(); done(`${out}/03-results.json`)
})().catch(e => { console.error(e); process.exit(2) })
