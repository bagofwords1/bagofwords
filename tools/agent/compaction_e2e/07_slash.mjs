import { open, shot, BASE, DIR } from './lib.mjs'
import fs from 'node:fs'
const rid = fs.readFileSync(DIR + 'report_id', 'utf8').trim()
const { browser, page } = await open({ scale: 2 })
await page.goto(BASE + '/reports/' + rid)
await page.waitForSelector('[contenteditable="true"]', { timeout: 120000 })
await page.waitForTimeout(4000)
const ed = page.locator('[contenteditable="true"]').last()
await ed.click()
await page.keyboard.type('/')
await page.waitForSelector('[data-testid="slash-menu"]', { timeout: 10000 })
await shot(page, '07-slash-menu')
await page.keyboard.type('co')
await page.keyboard.press('Tab')
await page.waitForTimeout(300)
await page.keyboard.type('focus on return rates and the West region', { delay: 5 })
await shot(page, '07-compact-typed')
const before = await page.evaluate(() => document.querySelector('[contenteditable="true"]:last-of-type')?.innerText)
console.log('composer text:', JSON.stringify(before))
await page.keyboard.press('Enter')
await page.waitForSelector('[data-testid="compact-status"]', { timeout: 10000 })
await shot(page, '07-compact-running')
await page.waitForSelector('[data-testid="compact-status"][data-phase="done"], [data-testid="compact-status"][data-phase="nothing"], [data-testid="compact-status"][data-phase="error"]', { timeout: 180000 })
const phase = await page.getAttribute('[data-testid="compact-status"]', 'data-phase')
console.log('phase', phase, '|', await page.innerText('[data-testid="compact-status"]'))
await shot(page, '07-compact-done')
// divider + summary popover
const div = page.locator('[data-testid="compaction-divider"]')
console.log('dividers', await div.count())
if (await div.count()) {
  await div.first().scrollIntoViewIfNeeded()
  await page.waitForTimeout(500)
  console.log('divider text', await div.first().innerText())
  await shot(page, '07-divider')
  await page.click('[data-testid="compaction-divider-button"]')
  await page.waitForSelector('[data-testid="compaction-summary-panel"]', { timeout: 10000 })
  await page.waitForTimeout(1500)
  await shot(page, '07-summary-popover')
  console.log('summary', (await page.innerText('[data-testid="compaction-summary-panel"]')).slice(0, 600))
}
await browser.close()
