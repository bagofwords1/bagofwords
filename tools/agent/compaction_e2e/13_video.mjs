import { chromium } from 'playwright'
import { BASE, DIR } from './lib.mjs'
import fs from 'node:fs'
const rid = fs.readFileSync(DIR + 'report_id', 'utf8').trim()
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' })
const ctx = await browser.newContext({ viewport: { width: 1280, height: 800 }, storageState: DIR + 'state.json', recordVideo: { dir: DIR + 'video', size: { width: 1280, height: 800 } } })
const page = await ctx.newPage()
await page.goto(BASE + '/reports/' + rid)
await page.waitForSelector('[contenteditable="true"]', { timeout: 120000 })
await page.waitForTimeout(4000)
await page.locator('[contenteditable="true"]').last().click()
await page.keyboard.type('/', { delay: 120 }); await page.waitForTimeout(900)
await page.keyboard.type('co', { delay: 150 }); await page.waitForTimeout(600)
await page.keyboard.press('Tab'); await page.waitForTimeout(400)
await page.keyboard.type('focus on Sports and Bikes', { delay: 45 }); await page.waitForTimeout(700)
await page.keyboard.press('Enter')
await page.waitForSelector('[data-testid="compact-status"][data-phase="done"], [data-testid="compact-status"][data-phase="nothing"]', { timeout: 180000 })
await page.waitForTimeout(2500)
await page.locator('[data-testid="compaction-divider"]').first().scrollIntoViewIfNeeded()
await page.waitForTimeout(800)
await page.click('[data-testid="compaction-divider-button"]')
await page.waitForTimeout(3000)
const v = page.video()
await ctx.close(); await browser.close()
console.log('video', await v.path())
