"""Regenerate backend/app/data_sources/clients/hpe_oneview/catalog.json.

The catalog is an execution ALLOW-LIST of read-only OneView REST resources.
Every field name below is camelCase exactly as the appliance returns it;
nested scalars are dotted (``mpHostInfo.mpHostName``). Evidence for each
resource is recorded in tools/hpe_oneview/SOURCES.md. Fields that could not
be verified against an SDK struct, SDK fixture or official example carry
``"inferred": true`` so the connector never silently invents a wire name.

Run: python3 tools/hpe_oneview/generate_catalog.py
"""

