S, I, N, B, A, O = "string", "integer", "number", "boolean", "array", "object"  # noqa: E741

COMMON = {
    "uri": (S, "Canonical resource URI, e.g. /rest/server-hardware/<uuid>; join key everywhere."),
    "name": (S, "Display name."),
    "category": (S, "Resource category, e.g. server-hardware."),
    "type": (S, "Resource schema type string, e.g. server-hardware-12."),
    "status": (S, "Health: OK, Warning, Critical, Disabled or Unknown."),
    "state": (S, "Lifecycle state (resource specific)."),
    "description": (S, "Free-text description."),
    "created": (S, "Creation timestamp (ISO-8601 UTC)."),
    "modified": (S, "Last modification timestamp (ISO-8601 UTC)."),
    "eTag": (S, "Entity tag for concurrency control."),
    "scopesUri": (S, "URI of the scopes assigned to the resource."),
}


def fields(*names, **extra):
    out = {}
    for n in names:
        out[n] = COMMON[n]
    out.update(extra)
    return {k: {"type": v[0], "description": v[1], **({"inferred": True} if len(v) > 2 and v[2] else {})} for k, v in out.items()}


RESOURCES = {}


def resource(name, path, kind, description, flds, filters=(), sortable=True, parents=(), defaults=(), **extra):
    RESOURCES[name] = {
        "path": path,
        "kind": kind,
        "description": description,
        "fields": flds,
        "filters": list(filters),
        "sortable": sortable,
        "parents": list(parents),
        "default_fields": list(defaults) or [k for k in flds if k in {"uri", "name", "status", "state"}],
        **extra,
    }


