test('late filtered list responses cannot replace the complete draft catalog', async ({page}) => {
  let releaseCatalog!: () => void
  let releaseList!: () => void
  let catalogStarted!: () => void
  let listStarted!: () => void
  const catalogGate = new Promise<void>(resolve => {releaseCatalog = resolve})
  const listGate = new Promise<void>(resolve => {releaseList = resolve})
  const catalogReady = new Promise<void>(resolve => {catalogStarted = resolve})
  const listReady = new Promise<void>(resolve => {listStarted = resolve})
  await page.goto(`/agents/${id}/tables`)
  const row = page.locator('li').filter({has:page.getByText('orders',{exact:true})})
  await row.getByRole('checkbox').uncheck()
  await page.route('**/full_schema?**', async route => {
    const url = new URL(route.request().url())
    if (url.searchParams.get('page_size') === '500' && url.searchParams.get('page') === '1') {
      const response = await route.fetch()
      catalogStarted()
      await catalogGate
      await route.fulfill({response})
    } else if (url.searchParams.get('page_size') === '100' && url.searchParams.get('search') === 'orders') {
      const response = await route.fetch()
      listStarted()
      await listGate
      await route.fulfill({response})
    } else await route.continue()
  })
  try {
    await page.getByRole('button',{name:'ERD',exact:true}).click()
    await catalogReady
    await page.getByRole('button',{name:'Filter tables',exact:true}).click()
    await page.getByRole('button',{name:'Unselected',exact:true}).click()
    await page.getByPlaceholder('Search tables...').fill('orders')
    await listReady
    releaseCatalog()
    await expect(page.getByTestId('tables-erd')).toBeVisible()
    await expect(page.getByTestId('erd-discovery')).toContainText('orders')
    const delayed = page.waitForResponse(response => response.url().includes('page_size=100') && response.url().includes('search=orders'))
    releaseList()
    await delayed
    await page.getByRole('button',{name:'Table',exact:true}).click()
    await expect(row.getByRole('checkbox')).toBeVisible()
    await expect(row.getByRole('checkbox')).not.toBeChecked()
    await expect(page.getByText('Unsaved changes',{exact:true})).toBeVisible()
  } finally {
    releaseCatalog()
    releaseList()
  }
})

