const node = (page: any, name: string) => page.getByTestId(`erd-node-${name}`)
async function allTables(request: any) {
  const tables: any[] = []
  let page = 1
  while (true) {
    const response = await request.get(`${seed.base_url}/api/data_sources/${id}/full_schema?page=${page}&page_size=500`, {headers})
    expect(response.ok()).toBeTruthy()
    const data = await response.json()
    tables.push(...data.tables)
    if (!data.has_more) return {tables}
    page++
  }
}
async function reset(request: any) {
  expect((await request.put(`${seed.base_url}/api/organization/onboarding`, {headers, data:{dismissed:true,completed:false}})).ok()).toBeTruthy()
  expect((await request.post(`${seed.base_url}/api/data_sources/${id}/bulk_update_tables`, {headers, data:{action:'deactivate'}})).ok()).toBeTruthy()
  expect((await request.put(`${seed.base_url}/api/data_sources/${id}/update_tables_status`, {headers, data:{activate:['orders'],deactivate:[]}})).ok()).toBeTruthy()
}
