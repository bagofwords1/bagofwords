<template>
  <div class="min-w-0">
    <ToolCallHeader :tool-execution="toolExecution" icon="heroicons-clipboard-document-check" :expanded="toolHeaderExpanded" @toggle="toolHeaderExpanded = !toolHeaderExpanded">
      <template #label>
      <template v-if="status === 'running'">{{ argName ? t('tools.createEval.draftingNamed', { name: argName }) : t('tools.createEval.drafting') }}</template>
      <template v-else-if="success">{{ t('tools.createEval.created') }}</template>
      <template v-else>{{ t('tools.createEval.notCreated') }}</template></template>
    </ToolCallHeader>
    <div v-show="toolHeaderExpanded" class="tool-call-details w-full min-w-0 mt-2">

    <div v-if="success" class="text-chat-2 text-gray-600 dark:text-gray-400">
      <div class="flex items-center py-1 px-1 rounded">
        <NuxtLink :to="`/agents`" class="font-medium text-gray-700 dark:text-gray-300 truncate hover:text-blue-600">
          {{ caseName || t('tools.createEval.unnamed') }}
        </NuxtLink>
        <span v-if="suiteName" class="ms-1.5 text-chat-3 px-1 py-0.5 rounded bg-gray-100 dark:bg-gray-800 text-gray-500 dark:text-gray-400 flex-shrink-0">{{ suiteName }}</span>
        <span v-if="status_field === 'draft'" class="ms-1 text-chat-3 px-1 py-0.5 rounded bg-amber-100 dark:bg-amber-950 text-amber-800 dark:text-amber-300 flex-shrink-0">{{ t('tools.createEval.statusDraft') }}</span>
        <span v-else-if="status_field === 'active'" class="ms-1 text-chat-3 px-1 py-0.5 rounded bg-green-100 dark:bg-green-900/50 text-green-800 dark:text-green-300 flex-shrink-0">{{ t('tools.createEval.statusActive') }}</span>
        <span v-if="autoGenerated" class="ms-1 text-chat-3 px-1 py-0.5 rounded bg-purple-100 dark:bg-purple-950 text-purple-800 dark:text-purple-300 flex-shrink-0">{{ t('tools.createEval.autoBadge') }}</span>
      </div>
      <div v-if="message" class="ms-1 mt-0.5 text-chat-2 text-gray-500 dark:text-gray-400">{{ message }}</div>
    </div>

    <div v-else-if="status !== 'running'" class="text-chat-2 text-gray-500 dark:text-gray-400 ms-1">
      {{ message || rejectedReason || t('tools.createEval.defaultMessage') }}
    </div>
  
    </div>
  </div>
</template>

<script setup lang="ts">
import ToolCallHeader from '~/components/tools/ToolCallHeader.vue'
import { ref as activityRef } from 'vue'
const toolHeaderExpanded = activityRef(false)

import { computed } from 'vue'
import { useResponseI18n } from '~/composables/useResponseI18n'

const { t } = useResponseI18n()

interface ToolExecution {
  id: string
  tool_name: string
  status: string
  result_json?: any
  arguments_json?: any
}

const props = defineProps<{ toolExecution: ToolExecution }>()

const status = computed(() => props.toolExecution?.status || '')

const result = computed<any>(() => props.toolExecution?.result_json || {})
const success = computed<boolean>(() => !!result.value?.success)
const caseName = computed<string>(() => result.value?.name || '')
const suiteName = computed<string>(() => result.value?.suite_name || '')
const status_field = computed<string>(() => result.value?.status || '')
const autoGenerated = computed<boolean>(() => !!result.value?.auto_generated)
const message = computed<string>(() => result.value?.message || '')
const rejectedReason = computed<string>(() => result.value?.rejected_reason || '')

const argName = computed<string>(() => {
  return props.toolExecution?.arguments_json?.name || ''
})
</script>

<style scoped>
.tool-call-details { overflow-wrap: anywhere; }
</style>
